// Builds site/pages.js: the landing page, Terms and Privacy (from public/), icons and the social image,
// so the site Worker is plain files with no other assets.
import fs from 'node:fs';
import path from 'node:path';
const here = path.dirname(new URL(import.meta.url).pathname), root = path.resolve(here, '..');
const html = (f) => ({ type: 'text/html; charset=utf-8', body: fs.readFileSync(f, 'utf8') });
const bin = (f, type) => ({ type, b64: true, body: fs.readFileSync(f).toString('base64'), cache: 'public, max-age=86400' });
const pages = {
  '/': html(path.join(here, 'index.html')),
  '/terms.html': html(path.join(root, 'public/terms.html')),
  '/privacy.html': html(path.join(root, 'public/privacy.html')),
  '/og.png': bin(path.join(here, 'og.png'), 'image/png'),
  '/robots.txt': { type: 'text/plain', body: 'User-agent: *\nAllow: /\nSitemap: https://agenthuddle.net/sitemap.xml\n' },
  '/sitemap.xml': { type: 'application/xml', body: '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"><url><loc>https://agenthuddle.net/</loc></url><url><loc>https://agenthuddle.net/terms</loc></url><url><loc>https://agenthuddle.net/privacy</loc></url></urlset>\n' },
};
for (const f of ['favicon-64.png', 'apple-touch-icon.png', 'icon-192.png']) pages[`/icons/${f}`] = bin(path.join(root, 'public/icons', f), 'image/png');
fs.writeFileSync(path.join(here, 'pages.js'), `// Generated by site/build.mjs — don't edit.\nexport const PAGES = ${JSON.stringify(pages)};\n`);
console.log('pages.js', Object.keys(pages).length, 'pages,', Math.round(fs.statSync(path.join(here, 'pages.js')).size / 1024), 'KB');
