// Builds relay/pages.js: the phone web app (shell.html with tunnel.mjs inlined), its icons and manifest,
// and the Terms and Privacy pages, so the relay Worker is two plain files with no other assets.
import fs from 'node:fs';
import path from 'node:path';
const here = path.dirname(new URL(import.meta.url).pathname), root = path.resolve(here, '..');
const tunnel = fs.readFileSync(path.join(root, 'local/tunnel.mjs'), 'utf8').replace(/^export\s+/gm, '');
const shell = fs.readFileSync(path.join(here, 'shell.html'), 'utf8').replace('/*TUNNEL*/', () => tunnel);
const pages = {
  '/': { type: 'text/html; charset=utf-8', body: shell },
  '/sw.js': { type: 'text/javascript; charset=utf-8', body: fs.readFileSync(path.join(here, 'sw.js'), 'utf8').replace('/*TUNNEL*/', () => tunnel) },
  '/manifest.webmanifest': { type: 'application/manifest+json', body: fs.readFileSync(path.join(root, 'public/manifest.webmanifest'), 'utf8'), cache: 'public, max-age=3600' },
  '/terms.html': { type: 'text/html; charset=utf-8', body: fs.readFileSync(path.join(root, 'public/terms.html'), 'utf8') },
  '/privacy.html': { type: 'text/html; charset=utf-8', body: fs.readFileSync(path.join(root, 'public/privacy.html'), 'utf8') },
};
for (const f of fs.readdirSync(path.join(root, 'public/icons'))) {
  pages[`/icons/${f}`] = { type: 'image/png', b64: true, body: fs.readFileSync(path.join(root, 'public/icons', f)).toString('base64'), cache: 'public, max-age=86400' };
}
fs.writeFileSync(path.join(here, 'pages.js'), `// Generated by relay/build.mjs — don't edit.\nexport const PAGES = ${JSON.stringify(pages)};\n`);
console.log('pages.js', Object.keys(pages).length, 'pages,', Math.round(fs.statSync(path.join(here, 'pages.js')).size / 1024), 'KB');
